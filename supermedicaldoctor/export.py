"""The chef export: what a meal planner needs to know about the household's health, and no more.

`export/chef.yaml` is generated from `people/*` in the same commit as every change, and at start
when it differs. It holds allergies, intolerances, diet rules, the medicines and supplements still
taken (name, kind, dose, slot, days, food) and the fasting windows of pending appointments in the
next 14 days. Nothing else ever leaves the person's folder through it: no conditions, lab values,
documents, doctors, places, what an appointment is for, why a medicine is taken, notes or birth
date. `FIELDS` is that list, and a test pins it.
"""

from __future__ import annotations

from collections.abc import Mapping
from datetime import datetime, timedelta
from zoneinfo import ZoneInfo

import yaml

from supermedicaldoctor.records import (
    PersonData,
    active,
    appt_start,
    as_date,
    dump_yaml,
    is_fasting,
)

HEADER = "# Generated by SuperMedicalDoctor. Do not edit: the next change overwrites it.\n"
FASTING_DAYS = 14
PERSON_FIELDS = ("allergies", "intolerances", "diet", "meds", "fasting")
MED_FIELDS = ("name", "kind", "dose", "slot", "days", "food")
FASTING_FIELDS = ("from", "until", "text")


def chef(people: Mapping[str, PersonData], now: datetime, tz: str) -> dict:
    """The export as a mapping, without its `generated` time."""
    zone = ZoneInfo(tz)
    today = now.astimezone(zone).date()
    out: dict = {}
    for pid in sorted(people):
        pd = people[pid]
        p = pd.profile
        allergies = []
        for a in p.get("allergies") or []:
            what = a.get("what") if isinstance(a, Mapping) else a
            if isinstance(what, str) and what:
                allergies.append(what)
        meds = []
        for m in pd.meds:
            if not isinstance(m, Mapping) or not active(m, today):
                continue
            since = as_date(m.get("since"))
            if since is not None and since > today:
                continue
            meds.append({k: m.get(k) for k in MED_FIELDS})
        fasting = []
        horizon = now + timedelta(days=FASTING_DAYS)
        for a in pd.appointments:
            if not isinstance(a, Mapping) or a.get("status", "pending") != "pending":
                continue
            start = appt_start(a, tz)
            if start is None or not now <= start <= horizon:
                continue
            for prep in a.get("prep") or []:
                if not isinstance(prep, Mapping) or not is_fasting(str(prep.get("text", ""))):
                    continue
                hours = prep.get("hours_before")
                if isinstance(hours, bool) or not isinstance(hours, int):
                    continue
                fasting.append(
                    {
                        "from": (start - timedelta(hours=hours)).isoformat(),
                        "until": start.isoformat(),
                        "text": str(prep.get("text")),
                    }
                )
        fasting.sort(key=lambda f: f["from"])
        out[pid] = {
            "allergies": allergies,
            "intolerances": [str(x) for x in p.get("intolerances") or [] if x],
            "diet": [str(x) for x in p.get("diet") or [] if x],
            "meds": meds,
            "fasting": fasting,
        }
    return out


def render(people: Mapping[str, PersonData], now: datetime, tz: str) -> str:
    """`export/chef.yaml` as text, stamped with `now`."""
    stamp = now.astimezone(ZoneInfo(tz)).replace(microsecond=0).isoformat()
    body = {"generated": stamp, "people": chef(people, now, tz)}
    return HEADER + dump_yaml(body)


def same(old_text: str | None, people: Mapping[str, PersonData], now: datetime, tz: str) -> bool:
    """Whether the export on disk already says what it would say now (its `generated` time
    aside), so a change that leaves the export as it was does not touch it."""
    if not old_text:
        return False
    try:
        old = yaml.safe_load(old_text)
    except yaml.YAMLError:
        return False
    if not isinstance(old, dict):
        return False
    return _plain(old.get("people")) == _plain(chef(people, now, tz))


def _plain(value):
    """The export as YAML would load it back (dates as dates, times as strings)."""
    return yaml.safe_load(dump_yaml(value))
